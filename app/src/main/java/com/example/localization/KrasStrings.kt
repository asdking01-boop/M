enum class AppLanguage(val code: String, val displayName: String, val isRtl: Boolean) {
    ARABIC("ar", "العربية", true),
    ENGLISH("en", "English", false);

    companion object {
        fun fromCode(code: String): AppLanguage =
            if (code == "en") ENGLISH else ARABIC
    }
}

